#!/usr/bin/env python3
"""music_direction.py — the MUSIC DIRECTOR's data: resources/music/direction.json

The visual novels' music is directed the way their scenes are: one JSON file is the
single source of truth, scripts/vn/MusicDirector.gd reads it at runtime, and this
tool keeps it honest.

    python3 godot/tools/music_direction.py suggest    # rebuild the *_auto sections from the
                                                       # catalog + scenes (authored sections untouched)
    python3 godot/tools/music_direction.py validate   # CI: every reference resolves
    python3 godot/tools/music_direction.py report     # coverage: which scenes get which music, and why

Sections of direction.json
  defaults        tuning: base intensity, attack / release seconds, leitmotif cooldown…
  lexicon         words that push intensity up (tension) or down (calm) when the director
                  infers intensity from the writing
  scenes          AUTHORED per-scene cue sheets: {track, intensity, beats:[{at, …}]}
  locales         AUTHORED background → track (bg src, e.g. "3d:diner_interior", per volume)
  characters      AUTHORED character key → {theme, leitmotif: true|false}
  locales_auto    GENERATED by `suggest` — bg srcs matched to same-volume catalog tracks
  characters_auto GENERATED by `suggest` — catalog "chars" tags on *_theme tracks
Authored entries always win over *_auto ones.
"""
import json, os, re, sys, glob, collections

