GODOT = os.path.dirname(HERE)
DIRECTION = os.path.join(GODOT, 'resources', 'music', 'direction.json')
CATALOG = os.path.join(GODOT, 'resources', 'music_catalog.json')
SCENES = os.path.join(GODOT, 'resources', 'scenes')

